CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_number VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(120),
    email VARCHAR(254),
    phone VARCHAR(40),
    address VARCHAR(500),
    description VARCHAR(2000),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_suppliers_supplier_number UNIQUE (supplier_number)
);

CREATE TABLE IF NOT EXISTS supplier_service_types (
    supplier_id BIGINT NOT NULL REFERENCES suppliers (id) ON DELETE CASCADE,
    service_type VARCHAR(30) NOT NULL,
    CONSTRAINT uk_supplier_service_type UNIQUE (supplier_id, service_type)
);

CREATE TEMPORARY TABLE legacy_supplier_names (
    normalized_name VARCHAR(150) NOT NULL,
    display_name VARCHAR(150) NOT NULL
) ON COMMIT DROP;

DO $$
BEGIN
    IF to_regclass('public.purchase_component_workflows') IS NOT NULL THEN
        ALTER TABLE purchase_component_workflows
            ADD COLUMN IF NOT EXISTS supplier_id BIGINT;
        EXECUTE '
            INSERT INTO legacy_supplier_names (normalized_name, display_name)
            SELECT lower(btrim(supplier_name)), min(btrim(supplier_name))
            FROM purchase_component_workflows
            WHERE supplier_name IS NOT NULL AND btrim(supplier_name) <> ''''
            GROUP BY lower(btrim(supplier_name))';
    END IF;

    IF to_regclass('public.manufacturing_component_workflows') IS NOT NULL THEN
        ALTER TABLE manufacturing_component_workflows
            ADD COLUMN IF NOT EXISTS supplier_id BIGINT;
        EXECUTE '
            INSERT INTO legacy_supplier_names (normalized_name, display_name)
            SELECT lower(btrim(supplier_name)), min(btrim(supplier_name))
            FROM manufacturing_component_workflows
            WHERE supplier_name IS NOT NULL AND btrim(supplier_name) <> ''''
            GROUP BY lower(btrim(supplier_name))';
    END IF;
END $$;

WITH unique_names AS (
    SELECT normalized_name, min(display_name) AS display_name
    FROM legacy_supplier_names
    GROUP BY normalized_name
),
numbered_names AS (
    SELECT display_name,
           row_number() OVER (ORDER BY normalized_name) AS row_number
    FROM unique_names
)
INSERT INTO suppliers (supplier_number, name, active, created_at, updated_at)
SELECT 'LEGACY-' || lpad(row_number::TEXT, 6, '0'), display_name, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM numbered_names;

CREATE UNIQUE INDEX IF NOT EXISTS uk_suppliers_normalized_name
    ON suppliers (lower(btrim(name)));

DO $$
BEGIN
    IF to_regclass('public.purchase_component_workflows') IS NOT NULL THEN
        UPDATE purchase_component_workflows workflow
        SET supplier_id = supplier.id
        FROM suppliers supplier
        WHERE workflow.supplier_id IS NULL
          AND workflow.supplier_name IS NOT NULL
          AND lower(btrim(workflow.supplier_name)) = lower(btrim(supplier.name));

        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint constraint_row
            WHERE constraint_row.conrelid = 'public.purchase_component_workflows'::regclass
              AND constraint_row.contype = 'f'
              AND constraint_row.confrelid = 'public.suppliers'::regclass
        ) THEN
            ALTER TABLE purchase_component_workflows
                ADD CONSTRAINT fk_purchase_workflow_supplier
                FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL;
        END IF;

        CREATE INDEX IF NOT EXISTS idx_purchase_workflow_supplier_id
            ON purchase_component_workflows (supplier_id);
    END IF;

    IF to_regclass('public.manufacturing_component_workflows') IS NOT NULL THEN
        UPDATE manufacturing_component_workflows workflow
        SET supplier_id = supplier.id
        FROM suppliers supplier
        WHERE workflow.supplier_id IS NULL
          AND workflow.supplier_name IS NOT NULL
          AND lower(btrim(workflow.supplier_name)) = lower(btrim(supplier.name));

        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint constraint_row
            WHERE constraint_row.conrelid = 'public.manufacturing_component_workflows'::regclass
              AND constraint_row.contype = 'f'
              AND constraint_row.confrelid = 'public.suppliers'::regclass
        ) THEN
            ALTER TABLE manufacturing_component_workflows
                ADD CONSTRAINT fk_manufacturing_workflow_supplier
                FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL;
        END IF;

        CREATE INDEX IF NOT EXISTS idx_manufacturing_workflow_supplier_id
            ON manufacturing_component_workflows (supplier_id);
    END IF;
END $$;

DO $$
BEGIN
    IF to_regclass('public.purchase_component_workflows') IS NOT NULL THEN
        INSERT INTO supplier_service_types (supplier_id, service_type)
        SELECT DISTINCT workflow.supplier_id, 'PURCHASE'
        FROM purchase_component_workflows workflow
        WHERE workflow.supplier_id IS NOT NULL
        ON CONFLICT DO NOTHING;
    END IF;

    IF to_regclass('public.manufacturing_component_workflows') IS NOT NULL THEN
        INSERT INTO supplier_service_types (supplier_id, service_type)
        SELECT DISTINCT workflow.supplier_id, 'MANUFACTURING'
        FROM manufacturing_component_workflows workflow
        WHERE workflow.supplier_id IS NOT NULL
        ON CONFLICT DO NOTHING;
    END IF;
END $$;
