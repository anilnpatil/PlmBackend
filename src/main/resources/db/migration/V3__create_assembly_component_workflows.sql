CREATE TABLE IF NOT EXISTS assembly_component_workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    design_part_id BIGINT NOT NULL UNIQUE
        REFERENCES design_register_parts (id) ON DELETE CASCADE,
    assembly_start_date DATE,
    assembly_complete_date DATE,
    assembly_status VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    CONSTRAINT ck_assembly_workflow_status
        CHECK (assembly_status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_assembly_workflow_dates
        CHECK (assembly_complete_date IS NULL
            OR (assembly_start_date IS NOT NULL AND assembly_complete_date >= assembly_start_date))
);
